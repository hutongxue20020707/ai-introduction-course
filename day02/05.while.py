"""
python 中的循环

循环就是"重复做同一件事"。写循环要记住四要素：

    1.循环变量    => 一开始先定好"从哪儿开始"
    2.循环条件    => 满足就继续做，不满足就停
    3.循环体      => 循环条件满足时，需要做的事情
    4.迭代条件    => 改变循环变量的值

python 里两种循环，用途不一样：

    for   —— 适合"把一串东西挨个处理一遍"（遍历）
             写法：for 变量 in 一串东西:

    while —— 适合"只要条件成立就一直做"（次数不固定）
             写法：while 条件:

为什么学 AI 要先学循环？因为"多轮对话"就是
"一直问、一直答，直到用户说再见" —— 那就是个循环。

运行：python 05.while.py
"""

# ===========================================================================
# 一、for 循环（老师课堂的例子）
#     for 会把你给的那串东西，从头到尾挨个取出来，每取一个就执行一次循环体
# ===========================================================================
a = "我开始学习循环了！"
for i in a:
    # print(i)          # 输出内容并换行
    print(i, end="")    # 输出内容不换行
print()                 # 收尾换行（复习第 06 课：end="" 是不换行）

# ---------------------------------------------------------------------------
# 补充 1：for 配 range()，专门用来"重复 n 次"
# ---------------------------------------------------------------------------
print()
print("--- range 试试 ---")
for i in range(3):          # range(3) 会依次给出 0、1、2
    print(f"第 {i + 1} 次循环（i 现在是 {i}）")

# range 还能指定起点和步长
for i in range(1, 6):       # 1、2、3、4、5（含头不含尾）
    print(i, end=" ")
print()

# ---------------------------------------------------------------------------
# 补充 2：for 遍历列表 —— 这是最常用的场景
# ---------------------------------------------------------------------------
print()
print("--- 遍历列表 ---")
fruits = ["苹果", "香蕉", "橘子"]
for fruit in fruits:
    print(f"篮子里有：{fruit}")

questions = ["什么是大模型？", "什么是提示词？", "什么是流式输出？"]
for idx, q in enumerate(questions, start=1):   # enumerate 能同时拿到序号
    print(f"第{idx}个问题：{q}")

# ===========================================================================
# 二、while 循环（老师课堂的例子）
#     四要素全都在注释里，照着看就行
# ===========================================================================
print()
print("--- while 循环 ---")

i = 1                       # 1.定义循环变量
while i <= 5:               # 2.判断循环条件是否满足
    print(f"小明跑步跑了第{i}圈")   # 3.执行循环体内容
    i += 1                  # 4.修改循环变量（少了这句就是"死循环"！）

print("程序执行完毕！")

# ---------------------------------------------------------------------------
# 补充 3：break 和 continue
#     break    —— 直接跳出整个循环
#     continue —— 跳过这一次，继续下一次
# ---------------------------------------------------------------------------
print()
print("--- break 和 continue ---")
for i in range(1, 11):
    if i == 4:
        continue            # 4 跳过不打印
    if i == 7:
        break               # 到 7 就整个结束
    print(i, end=" ")
print()

# ---------------------------------------------------------------------------
# 补充 4：累加器 —— 循环的经典用法
# ---------------------------------------------------------------------------
print()
print("--- 1 到 100 求和 ---")
total = 0                   # 累加器，先归零
for i in range(1, 101):
    total += i              # 等价于 total = total + i
print("1+2+3+...+100 =", total)

# ---------------------------------------------------------------------------
# 补充 5：死循环是怎么回事（知道怎么踩，才知道怎么躲）
# ---------------------------------------------------------------------------
