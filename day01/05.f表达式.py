"""
f表达式: 就是在字符串中使用变量，变量用{}包裹

例如：
    name="张三"
    print(f"{name}你好啊")

运行：python 05.f表达式.py
"""

# ---------------------------------------------------------------------------
# 一、老师课堂上的例子
# ---------------------------------------------------------------------------
name = "张三"
print(f"{name}你好，我是李四")

# ---------------------------------------------------------------------------
# 二、花括号里还能直接做运算、调用函数
# ---------------------------------------------------------------------------
age = 18
city = "长沙"
print(f"{name}今年{age}岁，明年{age + 1}岁")
print(f"他名字有 {len(name)} 个字")

# ---------------------------------------------------------------------------
# 三、为什么要先学这个？因为拼提示词就靠它
# 上一节（03 少样本）里那句 prompt = f\"\"\"...{instruction}...\"\"\" 用的就是这个
# ---------------------------------------------------------------------------
task = "提取时间、地点、人物"
text = "我计划着周末和小丽一起去爬岳麓山"
print(f"你的任务是：{task}")
print(f"要处理的文本：{text}")

# ---------------------------------------------------------------------------
# 四、三个必须注意的点（新手最容易栽在前两个）
# ---------------------------------------------------------------------------

# 1) 前面那个 f 不能省！省了就是普通字符串，{name} 会原样打出来
print(f"有 f ：{name}你好")
print("没 f ：{name}你好")          # 对比这行输出，能看到区别

# 2) 花括号里只能放"表达式"（能算出一个值的东西），不能放语句
#    f"{for i in range(3)}"    ← 这样写会语法报错
#    f"{len(name)}"            ← 这样写可以
print(f"名字长度：{len(name)}")

# 3) 想打印真正的花括号（比如在提示词里写 JSON 示例），要写两遍 {{ }}
print(f'JSON 示例：{{"time": "周末", "person": "我和小丽"}}')

# ---------------------------------------------------------------------------
# 五、小练习：把三个变量拼成一句话
# 目标输出： 你好，我是张三，来自长沙，今年18岁。
# ---------------------------------------------------------------------------
print(f"你好，我是{name}，来自{city}，今年{age}岁。")
